// Text for `key` in `language`, with `{name}` placeholders filled from `values`. Missing text falls back to English, then the key.
export function translate(language, key, values = {}) {
  const template = strings[language]?.[key] ?? strings.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (placeholder, name) => name in values ? String(values[name]) : placeholder);
}

export const translator = language => (key, values) => translate(isLanguage(language) ? language : DEFAULT_LANGUAGE, key, values);
export const english = translator(DEFAULT_LANGUAGE);
